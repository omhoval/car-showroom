const canTransition = (map, from, to) => Boolean(map[from] && map[from].includes(to));

function assertTransition(map, from, to, entity = 'record') {
  if (!canTransition(map, from, to)) {
    throw new ApiError('INVALID_STATE_TRANSITION', `Cannot change ${entity} from ${from} to ${to}`);
  }
}

